#!/usr/bin/env bash
# Part of the Agent Workspace Template (version in scripts/TEMPLATE_VERSION). Upgrades replace it.
# check-docs.sh: keeps docs/ findable and honest (see the template's docs/project-docs.md).
#   scripts/check-docs.sh          fail on a doc without frontmatter, a broken relative link, or a stale
#                                  docs/index.md; warn (WARN lines) when code a doc governs changed after it
#                                  was reviewed
#   scripts/check-docs.sh --write  regenerate docs/index.md from the frontmatter (never edit it by hand)
# Frontmatter, at the top of each doc:
#   ---
#   description: one line, at most 150 characters: what this doc is
#   read_when: the tasks that need it ("changing auth or sessions"), not keywords
#   governs: [src/auth/**]      optional: the code it describes (git pathspec globs)
#   reviewed: 2026-11-08        needed with governs: the last time someone checked it against the code
#   ---
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1
[[ -d docs ]] || exit 0
python3 -I - "${1:-}" <<'PY'
import os, re, subprocess, sys
write = sys.argv[1] == "--write"
INDEX = "docs/index.md"
problems, warnings, rows = [], [], []

def fields(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m: return None
    out, key = {}, None
    for line in m.group(1).split("\n"):
        item = re.match(r"\s+-\s+(.+)$", line)
        if item and key:
            out[key].append(item.group(1).strip().strip("\"'")); continue
        kv = re.match(r"([a-z_]+):\s*(.*?)\s*(#.*)?$", line)
        if not kv: continue
        k, v = kv.group(1), kv.group(2)
        key = None
        if v.startswith("["): out[k] = [x.strip().strip("\"'") for x in v.strip("[]").split(",") if x.strip()]
        elif not v: out[k], key = [], k
        else: out[k] = v.strip("\"'")
    return out

docs = sorted(os.path.join(d, f) for d, _, fs in os.walk("docs") for f in fs if f.endswith(".md"))
for path in docs:
    if path == INDEX: continue
    text = open(path, encoding="utf-8").read()
    f = fields(text)
    if f is None:
        problems.append(f"{path}: no frontmatter (description, read_when; see scripts/check-docs.sh)"); continue
    desc, when = f.get("description"), f.get("read_when")
    if not isinstance(desc, str) or not desc: problems.append(f"{path}: frontmatter needs description")
    elif len(desc) > 150: problems.append(f"{path}: description is {len(desc)} characters; keep it to 150")
    if not isinstance(when, str) or not when: problems.append(f"{path}: frontmatter needs read_when (the tasks that need this doc)")
    governs = f.get("governs") or []
    if isinstance(governs, str): governs = [governs]
    reviewed = f.get("reviewed")
    if governs and not (isinstance(reviewed, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", reviewed)):
        problems.append(f"{path}: governs needs reviewed: YYYY-MM-DD")
    elif governs:
        specs = [f":(glob){g}" for g in governs]
        changed = subprocess.run(["git", "log", "-1", "--format=%cs", "--", *specs], capture_output=True, text=True).stdout.strip()
        if changed and changed > reviewed:
            warnings.append(f"WARN {path}: code it governs changed {changed}, after it was reviewed {reviewed}")
    body = text.split("\n---\n", 1)[-1]
    for link in re.findall(r"\]\(([^)\s]+)\)", body):
        if re.match(r"[a-z]+:|#", link): continue
        target = os.path.normpath(os.path.join(os.path.dirname(path), link.split("#")[0]))
        if not os.path.exists(target): problems.append(f"{path}: broken link {link}")
    cell = lambda s: str(s or "").replace("|", "\\|")
    rows.append(f"| [{os.path.relpath(path, 'docs')}]({os.path.relpath(path, 'docs')}) | {cell(desc)} | {cell(when)} |")

index = "\n".join(["# Docs index", "",
    "Generated by `scripts/check-docs.sh --write` from each doc's frontmatter; don't edit it by hand.", "",
    "| Doc | What | Read when |", "|---|---|---|", *rows]) + "\n"
current = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else None
if write:
    if current != index:
        open(INDEX, "w", encoding="utf-8").write(index); print(f"wrote {INDEX}")
elif current != index:
    problems.append(f"{INDEX} is out of date: run scripts/check-docs.sh --write")
for w in warnings: print(w)
for p in problems: print(p)
sys.exit(1 if problems else 0)
PY
